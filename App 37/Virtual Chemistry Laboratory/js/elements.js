function shellsFor(z){
  const caps=[2,8,18,32,32,18,8];
  let remaining=z, shells=[];
  for(let cap of caps){
    if(remaining<=0) break;
    const take=Math.min(cap,remaining);
    shells.push(take);
    remaining-=take;
  }
  return shells;
}

